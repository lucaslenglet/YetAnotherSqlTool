/** "ALTER ROLE [r] ADD MEMBER [x]" for each role the principal belongs to. */
export function scriptRoleMemberships(principal: PrincipalRow): string {
    return [...principal.memberOf]
        .sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()))
        .map((role) => `ALTER ROLE ${q(role)} ADD MEMBER ${q(principal.name)}\n${GO}`)
        .join("");
}

export function scriptUserCreate(user: PrincipalRow): string {
    let text = `CREATE USER ${q(user.name)}`;
    if (user.type === "E" || user.type === "X") text += " FROM EXTERNAL PROVIDER";
    else if (user.loginName !== null && user.authenticationType !== "NONE") {
        text += ` FOR LOGIN ${q(user.loginName)}`;
    } else if (user.authenticationType === "NONE") text += " WITHOUT LOGIN";
    if (user.defaultSchema !== null) text += ` WITH DEFAULT_SCHEMA=${q(user.defaultSchema)}`;
    return `${text}\n${GO}${scriptRoleMemberships(user)}`;
}

