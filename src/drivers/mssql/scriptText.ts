const GO = "GO\n";
const twoPart = (schema: string | null, name: string) =>
    schema === null ? q(name) : `${q(schema)}.${q(name)}`;
const onOff = (value: boolean) => (value ? "ON" : "OFF");

/** SET ANSI_NULLS / QUOTED_IDENTIFIER lines that precede a module or a table. */
function setOptions(ansiNulls: boolean, quotedIdentifier: boolean): string {
    return `SET ANSI_NULLS ${onOff(ansiNulls)}\n${GO}SET QUOTED_IDENTIFIER ${onOff(quotedIdentifier)}\n${GO}`;
}

/** Sorts like SMO's collections: by name, ignoring case. */
function byName<T extends { name: string }>(items: T[]): T[] {
    return [...items].sort((a, b) => {
        const left = a.name.toLowerCase();
        const right = b.name.toLowerCase();
        return left < right ? -1 : left > right ? 1 : 0;
    });
}

/** "[int]", "[nvarchar](40)", "[decimal](10, 2)", "[varchar](max)", "[probe].[phone]". */
export function formatColumnType(column: {
    typeName: string;
    typeSchema: string;
    isUserDefined: boolean;
    maxLength: number;
    precision: number;
    scale: number;
}): string {
    if (column.isUserDefined) return twoPart(column.typeSchema, column.typeName);
    const name = q(column.typeName);
    const size = typeSize(column.typeName, column, ", ");
    return size === "" ? name : `${name}(${size})`;
}

/** The part between parentheses of a sized type, or "". */
function typeSize(
    typeName: string,
    column: { maxLength: number; precision: number; scale: number },
    decimalSeparator: string,
): string {
    switch (typeName) {
        case "char":
        case "varchar":
        case "binary":
        case "varbinary":
            return column.maxLength === -1 ? "max" : String(column.maxLength);
        case "nchar":
        case "nvarchar":
            return column.maxLength === -1 ? "max" : String(column.maxLength / 2);
        case "decimal":
        case "numeric":
            return `${column.precision}${decimalSeparator}${column.scale}`;
        case "datetime2":
        case "datetimeoffset":
        case "time":
            return String(column.scale);
        default:
            return "";
    }
}

/** Type of a parameter in the Execute template: "nvarchar(50)", "decimal(10,2)", "[s].[t]". */
function formatParameterType(parameter: ParameterRow): string {
    if (parameter.isUserDefined) return twoPart(parameter.typeSchema, parameter.typeName);
    const size = typeSize(parameter.typeName, parameter, ",");
    return size === "" ? parameter.typeName : `${parameter.typeName}(${size})`;
}

/** One column of CREATE TABLE / CREATE TYPE AS TABLE, without the leading tab. */
function columnDefinition(column: ColumnRow): string {
    if (column.computedDefinition !== null) {
        let text = `${q(column.name)}  AS ${column.computedDefinition}`;
        if (column.isPersisted) {
            text += " PERSISTED";
            if (!column.isNullable) text += " NOT NULL";
        }
        return text;
    }
    let text = `${q(column.name)} ${formatColumnType(column)}`;
    if (column.isSparse) text += " SPARSE ";
    if (column.isIdentity) {
        text += ` IDENTITY(${column.seedValue},${column.incrementValue})`;
        if (column.notForReplication) text += " NOT FOR REPLICATION";
    }
    if (column.isRowGuidCol) text += " ROWGUIDCOL ";
    if (column.generatedAlwaysType === 1 || column.generatedAlwaysType === 2) {
        text += ` GENERATED ALWAYS AS ROW ${column.generatedAlwaysType === 1 ? "START" : "END"}`;
        if (column.isHidden) text += " HIDDEN";
    }
    return `${text} ${column.isNullable ? "NULL" : "NOT NULL"}`;
}

