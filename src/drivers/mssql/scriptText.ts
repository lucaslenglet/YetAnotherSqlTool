/**
 * Text of the SQL Server "Script as Create / Drop / Alter / Execute" scripts, built from catalog
 * rows (see scriptCatalog.ts). Pure functions: no database access.
 *
 * The layout is the one SMO gives sqltoolsservice with vscode-mssql's scripting options, captured
 * in docs/reference/mssql-scripts.json (tools/sts-script-probe.js): SET options and GO lines, tabs,
 * the double spaces of "ADD  CONSTRAINT" or "IF  EXISTS", bracketed type names, index WITH lists.
 * Keep it byte-for-byte identical to the capture; test/drivers/mssql/scripts.test.ts checks it.
 */

import { quoteIdentifier as q } from "./sqlText";

