/** SMO's role drop: removes the members first. Its lines end with CRLF, as SMO writes them. */
export function scriptRoleDrop(name: string): string {
    const literal = name.replace(/'/g, "''");
    const lines = [
        "",
        "DECLARE @RoleName sysname",
        `set @RoleName = N'${literal}'`,
        "",
        "IF @RoleName <> N'public' and (select is_fixed_role from sys.database_principals where name = @RoleName) = 0",
        "BEGIN",
        "    DECLARE @RoleMemberName sysname",
        "    DECLARE Member_Cursor CURSOR FOR",
        "    select [name]",
        "    from sys.database_principals ",
        "    where principal_id in ( ",
        "        select member_principal_id",
        "        from sys.database_role_members",
        "        where role_principal_id in (",
        "            select principal_id",
        "            FROM sys.database_principals where [name] = @RoleName AND type = 'R'))",
        "",
        "    OPEN Member_Cursor;",
        "",
        "    FETCH NEXT FROM Member_Cursor",
        "    into @RoleMemberName",
        "    ",
        "    DECLARE @SQL NVARCHAR(4000)",
        "",
        "    WHILE @@FETCH_STATUS = 0",
        "    BEGIN",
        "        ",
        "        SET @SQL = 'ALTER ROLE '+ QUOTENAME(@RoleName,'[') +' DROP MEMBER '+ QUOTENAME(@RoleMemberName,'[')",
        "        EXEC(@SQL)",
        "        ",
        "        FETCH NEXT FROM Member_Cursor",
        "        into @RoleMemberName",
        "    END;",
        "",
        "    CLOSE Member_Cursor;",
        "    DEALLOCATE Member_Cursor;",
        "END",
        `DROP ROLE ${q(name)}`,
    ];
    return `${lines.join("\r\n")}\n${GO}`;
}

/** SMO never writes an application role's password: the script generates a random one. */
export function scriptApplicationRoleCreate(role: PrincipalRow): string {
    const schema = role.defaultSchema === null ? "" : `DEFAULT_SCHEMA = ${q(role.defaultSchema)}, `;
    const statement = `CREATE APPLICATION ROLE ${q(role.name)} WITH ${schema}`.replace(/'/g, "''");
    return [
        "/* To avoid disclosure of passwords, the password is generated in script. */",
        "declare @idx as int",
        "declare @placeholderPwd as nvarchar(64)",
        "declare @rnd as float",
        "select @idx = 0",
        "select @placeholderPwd = N''",
        "select @rnd = rand((@@CPU_BUSY % 100) + ((@@IDLE % 100) * 100) + ",
        "       (DATEPART(ss, GETDATE()) * 10000) + ((cast(DATEPART(ms, GETDATE()) as int) % 100) * 1000000))",
        "while @idx < 64",
        "begin",
        "   select @placeholderPwd = @placeholderPwd + char((cast((@rnd * 83) as int) + 43))",
        "   select @idx = @idx + 1",
        "select @rnd = rand()",
        "end",
        "declare @statement nvarchar(4000)",
        `select @statement = N'${statement}' + N'PASSWORD = N' + QUOTENAME(@placeholderPwd,'''')`,
        "EXEC dbo.sp_executesql @statement",
        GO,
    ].join("\n");
}

export const scriptApplicationRoleDrop = (name: string) =>
    `DROP APPLICATION ROLE  ${q(name)}\n${GO}`;
