/**
 * The module's definition with its first keyword, CREATE, replaced by ALTER, as SMO does for
 * "Script as Alter". Comments before it are kept, and so is the rest of the text, spacing included.
 */
export function toAlterDefinition(definition: string): string {
    let i = 0;
    while (i < definition.length) {
        if (/\s/.test(definition[i])) {
            i++;
        } else if (definition.startsWith("--", i)) {
            const end = definition.indexOf("\n", i);
            i = end === -1 ? definition.length : end + 1;
        } else if (definition.startsWith("/*", i)) {
            let depth = 1;
            i += 2;
            while (i < definition.length && depth > 0) {
                if (definition.startsWith("/*", i)) {
                    depth++;
                    i += 2;
                } else if (definition.startsWith("*/", i)) {
                    depth--;
                    i += 2;
                } else {
                    i++;
                }
            }
        } else {
            break;
        }
    }
    if (definition.slice(i, i + 6).toUpperCase() !== "CREATE") {
        throw new Error("The definition does not start with CREATE.");
    }
    return `${definition.slice(0, i)}ALTER${definition.slice(i + 6)}`;
}

function definitionOf(module: ModuleRow): string {
    if (module.definition === null) {
        throw new Error(
            `${twoPart(module.schemaName, module.name)} is encrypted: its text cannot be scripted.`,
        );
    }
    return module.definition;
}

/** The module with its SET lines; a trigger also gets the line that enables or disables it. */
export function scriptModuleCreate(module: ModuleRow): string {
    let text = setOptions(module.usesAnsiNulls, module.usesQuotedIdentifier);
    text += `${definitionOf(module)}\n${GO}`;
    const state = module.isDisabled ? "DISABLE" : "ENABLE";
    if (module.type === "TR" && module.parentType === "U") {
        text += `ALTER TABLE ${twoPart(module.parentSchema, module.parentName!)} ${state} TRIGGER ${q(module.name)}\n${GO}`;
    } else if (module.type === "DDL") {
        text += `${state} TRIGGER ${q(module.name)} ON DATABASE\n${GO}`;
    }
    return text;
}

export function scriptModuleAlter(module: ModuleRow): string {
    const text = setOptions(module.usesAnsiNulls, module.usesQuotedIdentifier);
    return `${text}${toAlterDefinition(definitionOf(module))}\n${GO}`;
}

const DROP_KEYWORDS: Record<string, string> = {
    V: "VIEW",
    P: "PROCEDURE",
    FN: "FUNCTION",
    IF: "FUNCTION",
    TF: "FUNCTION",
    TR: "TRIGGER",
};

export function scriptModuleDrop(module: ModuleRow): string {
    if (module.type === "DDL") return `DROP TRIGGER ${q(module.name)} ON DATABASE\n${GO}`;
    return `DROP ${DROP_KEYWORDS[module.type]} ${twoPart(module.schemaName, module.name)}\n${GO}`;
}

/** "Script as Create" of a view: the view, then its indexes and its triggers. */
export function scriptViewCreate(model: ViewModel): string {
    const { schemaName, name } = model.view;
    return (
        scriptModuleCreate(model.view) +
        orderedIndexes(model.indexes)
            .map((index) => scriptIndexCreate(schemaName!, name, index, true))
            .join("") +
        scriptTriggers(model.triggers)
    );
}

/** sqltoolsservice's "Script as Execute" template of a stored procedure. No newline after GO. */
export function scriptProcedureExecute(
    schema: string,
    name: string,
    parameters: ParameterRow[],
): string {
    let text = "DECLARE @RC int\n";
    for (const parameter of parameters) {
        text += `DECLARE ${parameter.name} ${formatParameterType(parameter)}\n`;
    }
    text += `\n-- TODO: Set parameter values here.\n\nEXECUTE @RC = ${twoPart(schema, name)} \n`;
    text += parameters
        .map((p, i) => `${i === 0 ? "   " : "  ,"}${p.name}${p.isOutput ? " OUTPUT" : ""}\n`)
        .join("");
    return `${text}GO`;
}

