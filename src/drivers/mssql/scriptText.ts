const PADDED_TYPES = new Set(["char", "varchar", "binary", "varbinary", "nchar", "nvarchar"]);

/** "\t[a] ASC,\n\t[b] DESC" */
function keyColumnList(index: IndexRow): string {
    return index.columns
        .filter((c) => !c.isIncluded)
        .sort((a, b) => a.keyOrdinal - b.keyOrdinal)
        .map((c) => `\t${q(c.columnName)} ${c.isDescending ? "DESC" : "ASC"}`)
        .join(",\n");
}

/** WITH (...) list of an index; constraints have no DROP_EXISTING, non-unique indexes no IGNORE_DUP_KEY. */
function indexOptions(index: IndexRow, isConstraint: boolean): string {
    const options = [
        `PAD_INDEX = ${onOff(index.isPadded)}`,
        `STATISTICS_NORECOMPUTE = ${onOff(index.noRecompute)}`,
        "SORT_IN_TEMPDB = OFF",
    ];
    if (isConstraint || index.isUnique)
        options.push(`IGNORE_DUP_KEY = ${onOff(index.ignoreDupKey)}`);
    if (!isConstraint) options.push("DROP_EXISTING = OFF");
    options.push(
        "ONLINE = OFF",
        `ALLOW_ROW_LOCKS = ${onOff(index.allowRowLocks)}`,
        `ALLOW_PAGE_LOCKS = ${onOff(index.allowPageLocks)}`,
    );
    if (index.fillFactor > 0) options.push(`FILLFACTOR = ${index.fillFactor}`);
    if (index.optimizeForSequentialKey !== null) {
        options.push(`OPTIMIZE_FOR_SEQUENTIAL_KEY = ${onOff(index.optimizeForSequentialKey)}`);
    }
    return `WITH (${options.join(", ")})`;
}

function dataSpaceClause(
    dataSpace: string | null,
    dataSpaceType: string | null,
    partitionColumn: string | null,
): string {
    if (dataSpace === null) return "";
    if (dataSpaceType === "PS" && partitionColumn !== null) {
        return ` ON ${q(dataSpace)}(${q(partitionColumn)})`;
    }
    return ` ON ${q(dataSpace)}`;
}

function indexDataSpace(index: IndexRow): string {
    return dataSpaceClause(index.dataSpace, index.dataSpaceType, index.partitionColumn);
}

const isClustered = (index: IndexRow) => index.type === 1;
const isConstraintIndex = (index: IndexRow) => index.isPrimaryKey || index.isUniqueConstraint;

/** Index types this generator writes; the others (XML, spatial, columnstore, hash) are not scripted. */
export const isScriptableIndex = (index: IndexRow) => index.type === 1 || index.type === 2;

/** SET lines SMO writes before an index on a view. */
const INDEXED_VIEW_OPTIONS =
    "SET ARITHABORT ON\nSET CONCAT_NULL_YIELDS_NULL ON\nSET QUOTED_IDENTIFIER ON\nSET ANSI_NULLS ON\nSET ANSI_PADDING ON\nSET ANSI_WARNINGS ON\nSET NUMERIC_ROUNDABORT OFF\n";

/** CREATE INDEX or ALTER TABLE ADD CONSTRAINT (PRIMARY KEY / UNIQUE) of one index, with its GO lines. */
export function scriptIndexCreate(
    schema: string,
    parentName: string,
    index: IndexRow,
    onView = false,
): string {
    if (!isScriptableIndex(index)) {
        throw new Error(
            `Scripting ${q(index.name)} is not supported: only clustered and nonclustered rowstore indexes are.`,
        );
    }
    const target = twoPart(schema, parentName);
    const kind = isClustered(index) ? "CLUSTERED" : "NONCLUSTERED";
    let text = "";
    if (onView) {
        text += INDEXED_VIEW_OPTIONS + GO;
    } else if (index.columns.some((c) => !c.isIncluded && PADDED_TYPES.has(c.typeName))) {
        text += `SET ANSI_PADDING ON\n${GO}`;
    }
    if (isConstraintIndex(index)) {
        const constraint = index.isPrimaryKey ? "PRIMARY KEY" : "UNIQUE";
        const add = index.isSystemNamed ? "ADD" : `ADD  CONSTRAINT ${q(index.name)}`;
        text += `ALTER TABLE ${target} ${add} ${constraint} ${kind} \n(\n${keyColumnList(index)}\n)`;
        return `${text}${indexOptions(index, true)}${indexDataSpace(index)}\n${GO}`;
    }
    text += `CREATE ${index.isUnique ? "UNIQUE " : ""}${kind} INDEX ${q(index.name)} ON ${target}\n(\n${keyColumnList(index)}\n)`;
    const included = index.columns.filter((c) => c.isIncluded).map((c) => q(c.columnName));
    if (included.length > 0) text += `\nINCLUDE(${included.join(",")}) `;
    if (index.filterDefinition !== null) text += `\nWHERE ${index.filterDefinition}\n`;
    return `${text}${indexOptions(index, false)}${indexDataSpace(index)}\n${GO}`;
}

export function scriptIndexDrop(schema: string, parentName: string, index: IndexRow): string {
    const target = twoPart(schema, parentName);
    const online = isClustered(index) ? " WITH ( ONLINE = OFF )" : "";
    if (isConstraintIndex(index)) {
        return `ALTER TABLE ${target} DROP CONSTRAINT ${q(index.name)}${online}\n${GO}`;
    }
    return `DROP INDEX ${q(index.name)} ON ${target}${online}\n${GO}`;
}

const ACTIONS: Record<string, string> = {
    CASCADE: "CASCADE",
    SET_NULL: "SET NULL",
    SET_DEFAULT: "SET DEFAULT",
};

export function scriptForeignKeyCreate(schema: string, table: string, fk: ForeignKeyRow): string {
    const target = twoPart(schema, table);
    const withCheck = fk.isNotTrusted ? "NOCHECK" : "CHECK";
    const add = fk.isSystemNamed ? "ADD" : `ADD  CONSTRAINT ${q(fk.name)}`;
    let text = `ALTER TABLE ${target}  WITH ${withCheck} ${add} FOREIGN KEY(${fk.columns.map(q).join(", ")})\n`;
    text += `REFERENCES ${twoPart(fk.refSchema, fk.refTable)} (${fk.refColumns.map(q).join(", ")})\n`;
    if (ACTIONS[fk.updateAction]) text += `ON UPDATE ${ACTIONS[fk.updateAction]}\n`;
    if (ACTIONS[fk.deleteAction]) text += `ON DELETE ${ACTIONS[fk.deleteAction]}\n`;
    text += GO;
    if (!fk.isSystemNamed) {
        text += `ALTER TABLE ${target} ${fk.isDisabled ? "NOCHECK" : "CHECK"} CONSTRAINT ${q(fk.name)}\n${GO}`;
    }
    return text;
}

export function scriptCheckCreate(schema: string, table: string, check: CheckRow): string {
    const target = twoPart(schema, table);
    const withCheck = check.isNotTrusted ? "NOCHECK" : "CHECK";
    const add = check.isSystemNamed ? "ADD" : `ADD  CONSTRAINT ${q(check.name)}`;
    let text = `ALTER TABLE ${target}  WITH ${withCheck} ${add} CHECK  (${check.definition})\n${GO}`;
    if (!check.isSystemNamed) {
        text += `ALTER TABLE ${target} ${check.isDisabled ? "NOCHECK" : "CHECK"} CONSTRAINT ${q(check.name)}\n${GO}`;
    }
    return text;
}

export function scriptConstraintDrop(schema: string, table: string, name: string): string {
    return `ALTER TABLE ${twoPart(schema, table)} DROP CONSTRAINT ${q(name)}\n${GO}`;
}

function scriptDefault(schema: string, table: string, column: ColumnRow): string {
    const named = column.defaultSystemNamed ? "" : ` CONSTRAINT ${q(column.defaultName!)} `;
    return `ALTER TABLE ${twoPart(schema, table)} ADD ${named} DEFAULT ${column.defaultDefinition} FOR ${q(column.name)}\n${GO}`;
}

