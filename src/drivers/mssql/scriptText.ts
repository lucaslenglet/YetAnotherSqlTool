export function scriptTypeCreate(type: TypeRow): string {
    const base = formatColumnType({
        typeName: type.baseTypeName,
        typeSchema: "sys",
        isUserDefined: false,
        maxLength: type.maxLength,
        precision: type.precision,
        scale: type.scale,
    });
    return `CREATE TYPE ${twoPart(type.schemaName, type.name)} FROM ${base} ${type.isNullable ? "NULL" : "NOT NULL"}\n${GO}`;
}

export function scriptTypeDrop(schema: string, name: string): string {
    return `DROP TYPE ${twoPart(schema, name)}\n${GO}`;
}

/** CREATE TYPE ... AS TABLE: columns, then indexes and constraints inline. */
export function scriptTableTypeCreate(model: TableTypeModel): string {
    const items = model.columns.map((column) => {
        const text = `\t${columnDefinition(column)}`;
        return column.defaultDefinition === null
            ? text
            : `${text} DEFAULT ${column.defaultDefinition}`;
    });
    const indexes = byName(model.indexes.filter(isScriptableIndex));
    for (const index of [
        ...indexes.filter((i) => !isConstraintIndex(i)),
        ...indexes.filter(isConstraintIndex),
    ]) {
        const kind = isClustered(index) ? "CLUSTERED" : "NONCLUSTERED";
        const columns = `\n(\n${keyColumnList(index)}\n)`;
        if (isConstraintIndex(index)) {
            const constraint = index.isPrimaryKey ? "PRIMARY KEY" : "UNIQUE";
            items.push(
                `\t${constraint} ${kind} ${columns}WITH (IGNORE_DUP_KEY = ${onOff(index.ignoreDupKey)})`,
            );
        } else {
            items.push(`\tINDEX ${q(index.name)} ${kind} ${columns}`);
        }
    }
    for (const check of byName(model.checks)) items.push(`\tCHECK (${check.definition})`);
    return `CREATE TYPE ${twoPart(model.schemaName, model.name)} AS TABLE(\n${items.join(",\n")}\n)\n${GO}`;
}

export function scriptSequenceCreate(sequence: SequenceRow): string {
    const type = formatColumnType({ ...sequence, maxLength: 0 });
    let text = `CREATE SEQUENCE ${twoPart(sequence.schemaName, sequence.name)} \n AS ${type}\n`;
    text += ` START WITH ${sequence.startValue}\n INCREMENT BY ${sequence.increment}\n`;
    text += ` MINVALUE ${sequence.minimumValue}\n MAXVALUE ${sequence.maximumValue}\n`;
    if (sequence.isCycling) text += " CYCLE \n";
    if (!sequence.isCached) text += " NO CACHE \n";
    else if (sequence.cacheSize === null) text += " CACHE \n";
    else text += ` CACHE  ${sequence.cacheSize} \n`;
    return text + GO;
}

export function scriptSequenceDrop(schema: string, name: string): string {
    return `DROP SEQUENCE ${twoPart(schema, name)}\n${GO}`;
}

export function scriptSynonymCreate(synonym: SynonymRow): string {
    return `CREATE SYNONYM ${twoPart(synonym.schemaName, synonym.name)} FOR ${synonym.baseObjectName}\n${GO}`;
}

export function scriptSynonymDrop(schema: string, name: string): string {
    return `DROP SYNONYM ${twoPart(schema, name)}\n${GO}`;
}

