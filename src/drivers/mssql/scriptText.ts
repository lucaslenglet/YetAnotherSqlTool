/** CREATE TABLE statement alone, with its SET lines. */
export function scriptCreateTableStatement(model: TableModel): string {
    const { table } = model;
    const lines = model.columns.map((column) => `\t${columnDefinition(column)}`);
    if (table.periodStart !== null && table.periodEnd !== null) {
        lines.push(`\tPERIOD FOR SYSTEM_TIME (${q(table.periodStart)}, ${q(table.periodEnd)})`);
    }
    let text = setOptions(table.usesAnsiNulls, true);
    text += `CREATE TABLE ${twoPart(table.schemaName, table.name)}(\n${lines.join(",\n")}\n)`;
    text += dataSpaceClause(table.dataSpace, table.dataSpaceType, table.partitionColumn);
    if (table.lobDataSpace !== null) text += ` TEXTIMAGE_ON ${q(table.lobDataSpace)}`;
    if (table.temporalType === 2 && table.historyName !== null) {
        text += `\nWITH\n(\nSYSTEM_VERSIONING = ON (HISTORY_TABLE = ${twoPart(table.historySchema, table.historyName)})\n)`;
    }
    return `${text}\n${GO}`;
}

/** Indexes in SMO's order: the clustered one first, then by name. */
export function orderedIndexes(indexes: IndexRow[]): IndexRow[] {
    const sorted = byName(indexes.filter(isScriptableIndex));
    return [...sorted.filter(isClustered), ...sorted.filter((i) => !isClustered(i))];
}

/** DEFAULT constraints, in column order. */
export function scriptDefaults(model: TableModel): string {
    return model.columns
        .filter((c) => c.defaultDefinition !== null)
        .map((c) => scriptDefault(model.table.schemaName, model.table.name, c))
        .join("");
}

export function scriptForeignKeys(model: TableModel): string {
    const { schemaName, name } = model.table;
    return byName(model.foreignKeys)
        .map((fk) => scriptForeignKeyCreate(schemaName, name, fk))
        .join("");
}

export function scriptChecks(model: TableModel): string {
    const { schemaName, name } = model.table;
    return byName(model.checks)
        .map((check) => scriptCheckCreate(schemaName, name, check))
        .join("");
}

export function scriptTriggers(triggers: ModuleRow[]): string {
    return byName(triggers)
        .map((trigger) => scriptModuleCreate(trigger))
        .join("");
}

/** "Script as Create" of a table: the table, its indexes, defaults, foreign keys, checks and triggers. */
export function scriptTableCreate(model: TableModel): string {
    const { schemaName, name } = model.table;
    return (
        scriptCreateTableStatement(model) +
        orderedIndexes(model.indexes)
            .map((index) => scriptIndexCreate(schemaName, name, index))
            .join("") +
        scriptDefaults(model) +
        scriptForeignKeys(model) +
        scriptChecks(model) +
        scriptTriggers(model.triggers)
    );
}

export function scriptTableDrop(table: TableRow): string {
    const target = twoPart(table.schemaName, table.name);
    let text = "";
    if (table.temporalType === 2)
        text += `ALTER TABLE ${target} SET ( SYSTEM_VERSIONING = OFF  )\n${GO}`;
    // The object name in OBJECT_ID is a Unicode literal of the quoted name.
    const literal = target.replace(/'/g, "''");
    text += `IF  EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'${literal}') AND type in (N'U'))\n`;
    return `${text}DROP TABLE ${target}\n${GO}`;
}

