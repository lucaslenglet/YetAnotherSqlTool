// Views
// ---------------------------------------------------------------------------

function viewStatement(view: PgView, orReplace: boolean): string {
    const definition = view.definition.replace(/;\s*$/, "");
    if (view.materialized) {
        return `CREATE MATERIALIZED VIEW ${view.qualifiedName}${view.options.length > 0 ? ` WITH (${view.options.join(", ")})` : ""} AS\n${definition}\n  WITH ${view.populated ? "" : "NO "}DATA;\n`;
    }
    const options = view.options.length > 0 ? ` WITH (${view.options.join(", ")})` : "";
    const check =
        view.checkOption === null ? "" : `\n  WITH ${view.checkOption.toUpperCase()} CHECK OPTION`;
    return `CREATE ${orReplace ? "OR REPLACE " : ""}VIEW ${view.qualifiedName}${options} AS\n${definition}${check};\n`;
}

function viewExtras(view: PgView): string {
    const kind = view.materialized ? "MATERIALIZED VIEW" : "VIEW";
    return (
        commentOn(`${kind} ${view.qualifiedName}`, view.comment) +
        view.columnComments
            .map((c) => commentOn(`COLUMN ${view.qualifiedName}.${c.name}`, c.comment))
            .join("")
    );
}

function viewIndexes(view: PgView): string {
    return view.indexes
        .map((i) => `\n${i.definition};\n${commentOn(`INDEX ${i.qualifiedName}`, i.comment)}`)
        .join("");
}

export function scriptViewCreate(view: PgView): string {
    return (
        viewStatement(view, false) +
        viewExtras(view) +
        viewIndexes(view) +
        view.triggers.map((t) => `\n${scriptTriggerCreate(view.qualifiedName, t)}`).join("")
    );
}

/** CREATE OR REPLACE VIEW; a materialized view cannot be replaced, so it is dropped and created. */
export function scriptViewAlter(view: PgView): string {
    if (!view.materialized) return viewStatement(view, true);
    return (
        "-- A materialized view cannot be replaced: it is dropped and created again, with its indexes.\n" +
        scriptViewDrop(view) +
        "\n" +
        viewStatement(view, false) +
        viewExtras(view) +
        viewIndexes(view)
    );
}

export const scriptViewDrop = (view: { qualifiedName: string; materialized: boolean }) =>
    `DROP ${view.materialized ? "MATERIALIZED " : ""}VIEW IF EXISTS ${view.qualifiedName};\n`;

