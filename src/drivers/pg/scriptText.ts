export const scriptSchemaCreate = (name: string, comment: string | null) =>
    `CREATE SCHEMA ${name};\n${commentOn(`SCHEMA ${name}`, comment)}`;
export const scriptSchemaDrop = (name: string) => `DROP SCHEMA IF EXISTS ${name};\n`;

export function scriptTypeCreate(type: PgType): string {
    let text: string;
    switch (type.kind) {
        case "d": {
            text = `CREATE DOMAIN ${type.qualifiedName} AS ${type.baseType}`;
            if (type.collation !== null) text += ` COLLATE ${type.collation}`;
            if (type.defaultExpression !== null) text += ` DEFAULT ${type.defaultExpression}`;
            if (type.notNull) text += " NOT NULL";
            text += type.constraints.map(([name, def]) => `\n\tCONSTRAINT ${name} ${def}`).join("");
            break;
        }
        case "e":
            text = `CREATE TYPE ${type.qualifiedName} AS ENUM (\n${type.labels.map((l) => `    ${l}`).join(",\n")}\n)`;
            break;
        case "r":
            text = `CREATE TYPE ${type.qualifiedName} AS RANGE (\n${[`subtype = ${type.baseType}`, ...type.rangeOptions].map((o) => `    ${o}`).join(",\n")}\n)`;
            break;
        default:
            text = `CREATE TYPE ${type.qualifiedName} AS (\n${type.attributes
                .map(
                    (a) =>
                        `    ${a.name} ${a.type}${a.collation === null ? "" : ` COLLATE ${a.collation}`}`,
                )
                .join(",\n")}\n)`;
    }
    const kind = type.kind === "d" ? "DOMAIN" : "TYPE";
    return `${text};\n${commentOn(`${kind} ${type.qualifiedName}`, type.comment)}`;
}

export const scriptTypeDrop = (type: { qualifiedName: string; kind: string }) =>
    `DROP ${type.kind === "d" ? "DOMAIN" : "TYPE"} IF EXISTS ${type.qualifiedName};\n`;
