// Functions and procedures
// ---------------------------------------------------------------------------

const routineKind = (routine: PgRoutine) => (routine.isProcedure ? "PROCEDURE" : "FUNCTION");
const routineSignature = (routine: PgRoutine) =>
    `${routine.qualifiedName}(${routine.identityArguments})`;

function routineStatement(routine: PgRoutine, orReplace: boolean): string {
    let definition = routine.definition.replace(/\s+$/, "");
    if (!orReplace) definition = definition.replace(/^CREATE OR REPLACE /, "CREATE ");
    return `${definition};\n`;
}

export function scriptRoutineCreate(routine: PgRoutine): string {
    return (
        routineStatement(routine, false) +
        commentOn(`${routineKind(routine)} ${routineSignature(routine)}`, routine.comment)
    );
}

export const scriptRoutineAlter = (routine: PgRoutine) => routineStatement(routine, true);

export const scriptRoutineDrop = (routine: PgRoutine) =>
    `DROP ${routineKind(routine)} IF EXISTS ${routineSignature(routine)};\n`;

/**
 * "Script as Execute" of a procedure, in the spirit of sqltoolsservice's template: every argument
 * is listed with a NULL of its type, to be replaced by a value.
 */
export function scriptProcedureExecute(routine: PgRoutine): string {
    const values = routine.arguments
        .filter((a) => a.mode !== "t")
        .map((a) => {
            const value = `${a.mode === "v" ? "VARIADIC " : ""}NULL::${a.type}`;
            return `    ${a.name === "" ? "" : `${a.name} => `}${value}`;
        });
    const list = values.length === 0 ? "()" : `(\n${values.join(",\n")}\n)`;
    return `-- TODO: Set parameter values here.\n\nCALL ${routine.qualifiedName}${list};\n`;
}

