/**
 * Text of the PostgreSQL "Script as Create / Drop / Alter / Execute" scripts, built from catalog
 * rows (see scriptCatalog.ts). Pure functions: no database access.
 *
 * There is no Microsoft reference for PostgreSQL: the scripts follow pg_dump's style. Names come
 * already quoted (quote_ident) and schema-qualified, and expressions, constraints, indexes, views
 * and functions come from the server's own deparsers (pg_get_expr, pg_get_constraintdef,
 * pg_get_indexdef, pg_get_viewdef, pg_get_functiondef, pg_get_triggerdef), read with an empty
 * search_path so that every name they print is qualified. Drop scripts use IF EXISTS.
 */

export interface PgColumn {
    /** Quoted name. */
    name: string;
    /** format_type(). */
    type: string;
    /** Qualified, quoted collation when it is not the type's default. */
    collation: string | null;
    notNull: boolean;
    /** pg_get_expr() of the default, or null. */
    defaultExpression: string | null;
    /** "" none, "a" GENERATED ALWAYS, "d" GENERATED BY DEFAULT (identity columns). */
    identity: string;
    identitySequence: PgSequence | null;
    /** pg_get_expr() of a stored generated column. */
    generatedExpression: string | null;
    /** quote_literal() of the comment, or null. */
    comment: string | null;
}

export interface PgConstraint {
    name: string;
    /** p primary key, u unique, f foreign key, c check, x exclusion. */
    type: string;
    /** pg_get_constraintdef(), e.g. "PRIMARY KEY (id)", "CHECK ((qty > 0)) NOT VALID". */
    definition: string;
    validated: boolean;
    comment: string | null;
}

export interface PgIndex {
    /** Qualified, quoted name (for DROP INDEX). */
    qualifiedName: string;
    name: string;
    /** pg_get_indexdef(). */
    definition: string;
    /** Name of the constraint the index belongs to (primary key, unique, exclusion), or null. */
    constraintName: string | null;
    comment: string | null;
}

export interface PgTrigger {
    name: string;
    /** pg_get_triggerdef(). */
    definition: string;
    /** pg_trigger.tgenabled: O enabled, D disabled, R replica, A always. */
    enabled: string;
    comment: string | null;
}

export interface PgSequence {
    oid?: number;
    /** Qualified, quoted name. */
    qualifiedName: string;
    /** format_type() of the sequence's type. */
    type: string;
    start: string;
    increment: string;
    min: string;
    max: string;
    cache: string;
    cycle: boolean;
    /** "schema.table.column" (quoted) for a sequence owned by a column (serial), or null. */
    ownedBy: string | null;
    comment: string | null;
}

export interface PgTable {
    /** pg_class oid (the database script orders objects with it). */
    oid?: number;
    qualifiedName: string;
    /** r table, p partitioned table. */
    kind: string;
    unlogged: boolean;
    /** pg_get_partkeydef() of a partitioned table, or null. */
    partitionKey: string | null;
    /** For a partition: its parent (qualified) and pg_get_expr() of its bound. */
    partitionOf: string | null;
    partitionBound: string | null;
    /** reloptions, e.g. ["fillfactor=70"]. */
    options: string[];
    rowSecurity: boolean;
    forceRowSecurity: boolean;
    comment: string | null;
    columns: PgColumn[];
    /** The table's own constraints (not those inherited by a partition), NOT NULL excluded. */
    constraints: PgConstraint[];
    /** Indexes that are not inherited from a partitioned parent. */
    indexes: PgIndex[];
    triggers: PgTrigger[];
    /** Sequences owned by a column that is not an identity column (serial). */
    ownedSequences: PgSequence[];
    partitions: PgTable[];
}

export interface PgView {
    qualifiedName: string;
    materialized: boolean;
    /** pg_get_viewdef(), which ends with ";". */
    definition: string;
    options: string[];
    /** "local" or "cascaded" for WITH CHECK OPTION, or null. */
    checkOption: string | null;
    populated: boolean;
    comment: string | null;
    columnComments: Array<{ name: string; comment: string }>;
    indexes: PgIndex[];
    triggers: PgTrigger[];
}

export interface PgArgument {
    /** Quoted name, or "" for an unnamed argument. */
    name: string;
    /** i IN, o OUT, b INOUT, v VARIADIC, t TABLE. */
    mode: string;
    type: string;
}

export interface PgRoutine {
    /** Qualified, quoted name without arguments. */
    qualifiedName: string;
    /** pg_get_function_identity_arguments(). */
    identityArguments: string;
    isProcedure: boolean;
    /** pg_get_functiondef(), "CREATE OR REPLACE ..." ending with a newline. */
    definition: string;
    arguments: PgArgument[];
    comment: string | null;
}

export interface PgType {
    qualifiedName: string;
    /** d domain, e enum, c composite, r range. */
    kind: string;
    /** Domain: base type; range: subtype. */
    baseType: string | null;
    collation: string | null;
    notNull: boolean;
    defaultExpression: string | null;
    /** Domain constraints: [quoted name, pg_get_constraintdef()]. */
    constraints: Array<[string, string]>;
    /** Enum labels, already quoted as literals. */
    labels: string[];
    /** Composite attributes. */
    attributes: Array<{ name: string; type: string; collation: string | null }>;
    /** Range options other than the subtype, e.g. "subtype_diff = pg_catalog.float8mi". */
    rangeOptions: string[];
    comment: string | null;
}

// ---------------------------------------------------------------------------

const commentOn = (target: string, comment: string | null) =>
    comment === null ? "" : `\nCOMMENT ON ${target} IS ${comment};\n`;

/** Sequence options, one per line, as pg_dump writes them. */
function sequenceOptions(sequence: PgSequence, indent: string, withType = true): string[] {
    const ascending = !sequence.increment.startsWith("-");
    const limits = TYPE_LIMITS[sequence.type] ?? TYPE_LIMITS.bigint;
    const defaultMin = ascending ? "1" : limits[0];
    const defaultMax = ascending ? limits[1] : "-1";
    const lines = [];
    if (withType && sequence.type !== "bigint") lines.push(`AS ${sequence.type}`);
    lines.push(`START WITH ${sequence.start}`, `INCREMENT BY ${sequence.increment}`);
    lines.push(sequence.min === defaultMin ? "NO MINVALUE" : `MINVALUE ${sequence.min}`);
    lines.push(sequence.max === defaultMax ? "NO MAXVALUE" : `MAXVALUE ${sequence.max}`);
    lines.push(`CACHE ${sequence.cache}`);
    if (sequence.cycle) lines.push("CYCLE");
    return lines.map((line) => indent + line);
}

const TYPE_LIMITS: Record<string, [string, string]> = {
    smallint: ["-32768", "32767"],
    integer: ["-2147483648", "2147483647"],
    bigint: ["-9223372036854775808", "9223372036854775807"],
};

export function scriptSequenceCreate(sequence: PgSequence, withOwner = true): string {
    let text = `CREATE SEQUENCE ${sequence.qualifiedName}\n${sequenceOptions(sequence, "    ").join("\n")};\n`;
    if (withOwner && sequence.ownedBy !== null) {
        text += `\nALTER SEQUENCE ${sequence.qualifiedName} OWNED BY ${sequence.ownedBy};\n`;
    }
    return text + commentOn(`SEQUENCE ${sequence.qualifiedName}`, sequence.comment);
}

export const scriptSequenceDrop = (sequence: { qualifiedName: string }) =>
    `DROP SEQUENCE IF EXISTS ${sequence.qualifiedName};\n`;

function columnDefinition(column: PgColumn): string {
    let text = `${column.name} ${column.type}`;
    if (column.collation !== null) text += ` COLLATE ${column.collation}`;
    if (column.generatedExpression !== null) {
        text += ` GENERATED ALWAYS AS (${column.generatedExpression}) STORED`;
    } else if (column.defaultExpression !== null) {
        text += ` DEFAULT ${column.defaultExpression}`;
    }
    if (column.identity !== "" && column.identitySequence !== null) {
        // The sequence of an identity column has the column's type: AS would be refused.
        const options = sequenceOptions(column.identitySequence, "", false).join(" ");
        const kind = column.identity === "a" ? "ALWAYS" : "BY DEFAULT";
        text += ` GENERATED ${kind} AS IDENTITY (SEQUENCE NAME ${column.identitySequence.qualifiedName} ${options})`;
    }
    if (column.notNull) text += " NOT NULL";
    return text;
}

/** Checks that are written inside CREATE TABLE (the validated ones, as pg_dump does). */
const isInlineCheck = (c: PgConstraint) => c.type === "c" && c.validated;

/** CREATE TABLE with its columns and checks, then the partitions' CREATE TABLE. */
export function scriptCreateTableStatement(table: PgTable): string {
    const unlogged = table.unlogged ? "UNLOGGED " : "";
    let text: string;
    if (table.partitionOf !== null) {
        text = `CREATE ${unlogged}TABLE ${table.qualifiedName} PARTITION OF ${table.partitionOf}`;
        const checks = table.constraints.filter(isInlineCheck);
        if (checks.length > 0) {
            text += ` (\n${checks.map((c) => `    CONSTRAINT ${c.name} ${c.definition}`).join(",\n")}\n)`;
        }
        text += `\n${table.partitionBound}`;
    } else {
        const items = [
            ...table.columns.map((c) => `    ${columnDefinition(c)}`),
            ...table.constraints
                .filter(isInlineCheck)
                .map((c) => `    CONSTRAINT ${c.name} ${c.definition}`),
        ];
        text = `CREATE ${unlogged}TABLE ${table.qualifiedName} (\n${items.join(",\n")}\n)`;
    }
    if (table.partitionKey !== null) text += `\nPARTITION BY ${table.partitionKey}`;
    if (table.options.length > 0) text += `\nWITH (${table.options.join(", ")})`;
    return `${text};\n`;
}

const alterTable = (table: PgTable) =>
    table.kind === "p"
        ? `ALTER TABLE ${table.qualifiedName}`
        : `ALTER TABLE ONLY ${table.qualifiedName}`;

export function scriptConstraintCreate(table: PgTable, constraint: PgConstraint): string {
    return (
        `${alterTable(table)}\n    ADD CONSTRAINT ${constraint.name} ${constraint.definition};\n` +
        commentOn(`CONSTRAINT ${constraint.name} ON ${table.qualifiedName}`, constraint.comment)
    );
}

export const scriptConstraintDrop = (table: { qualifiedName: string }, name: string) =>
    `ALTER TABLE IF EXISTS ${table.qualifiedName} DROP CONSTRAINT IF EXISTS ${name};\n`;

/** An index: its CREATE INDEX, or the ALTER TABLE of the constraint it belongs to. */
export function scriptIndexCreate(table: PgTable, index: PgIndex): string {
    if (index.constraintName !== null) {
        const constraint = table.constraints.find((c) => c.name === index.constraintName);
        if (constraint) return scriptConstraintCreate(table, constraint);
    }
    // On a partitioned table pg_get_indexdef says "ON ONLY": without ONLY the index cascades.
    const definition = index.definition.replace(/ ON ONLY /, " ON ");
    return `${definition};\n` + commentOn(`INDEX ${index.qualifiedName}`, index.comment);
}

export function scriptIndexDrop(table: PgTable, index: PgIndex): string {
    if (index.constraintName !== null) return scriptConstraintDrop(table, index.constraintName);
    return `DROP INDEX IF EXISTS ${index.qualifiedName};\n`;
}

const TRIGGER_STATES: Record<string, string> = {
    D: "DISABLE TRIGGER",
    R: "ENABLE REPLICA TRIGGER",
    A: "ENABLE ALWAYS TRIGGER",
};

export function scriptTriggerCreate(target: string, trigger: PgTrigger): string {
    let text = `${trigger.definition};\n`;
    const state = TRIGGER_STATES[trigger.enabled];
    if (state) text += `\nALTER TABLE ${target} ${state} ${trigger.name};\n`;
    return text + commentOn(`TRIGGER ${trigger.name} ON ${target}`, trigger.comment);
}

export const scriptTriggerDrop = (target: string, name: string) =>
    `DROP TRIGGER IF EXISTS ${name} ON ${target};\n`;

/**
 * Constraints written after CREATE TABLE: primary keys, unique keys and exclusions right after it;
 * foreign keys and NOT VALID checks (which existing rows may break) after the data.
 */
export const lateConstraints = (table: PgTable, afterData: boolean) =>
    table.constraints.filter((c) =>
        afterData
            ? c.type === "f" || (c.type === "c" && !c.validated)
            : ["p", "u", "x"].includes(c.type),
    );

const indexesWithoutConstraint = (table: PgTable) =>
    table.indexes.filter((i) => i.constraintName === null);

function tableComments(table: PgTable): string {
    return (
        commentOn(`TABLE ${table.qualifiedName}`, table.comment) +
        table.columns
            .map((c) => commentOn(`COLUMN ${table.qualifiedName}.${c.name}`, c.comment))
            .join("")
    );
}

function rowSecurity(table: PgTable): string {
    let text = "";
    if (table.rowSecurity)
        text += `\nALTER TABLE ${table.qualifiedName} ENABLE ROW LEVEL SECURITY;\n`;
    if (table.forceRowSecurity)
        text += `\nALTER TABLE ${table.qualifiedName} FORCE ROW LEVEL SECURITY;\n`;
    return text;
}

/** Parts of a table's script, so that the database script can put data and keys in between. */
export interface TableScriptParts {
    /** Owned sequences, CREATE TABLE (and the partitions'), primary/unique keys, comments. */
    table: string;
    /** OWNED BY of the serial sequences. */
    sequenceOwners: string;
    /** Foreign keys, indexes, triggers, row level security, recursively for the partitions. */
    rest: string;
}

/** All the partitions of a table, depth first. */
export function allPartitions(table: PgTable): PgTable[] {
    return table.partitions.flatMap((p) => [p, ...allPartitions(p)]);
}

export function tableScriptParts(table: PgTable): TableScriptParts {
    const tables = [table, ...allPartitions(table)];
    const sequences = tables.flatMap((t) => t.ownedSequences);
    const join = (texts: string[]) => texts.filter((t) => t !== "").join("\n");
    return {
        table: join([
            ...sequences.map((s) => scriptSequenceCreate(s, false)),
            ...tables.map(
                (t) =>
                    scriptCreateTableStatement(t) +
                    lateConstraints(t, false)
                        .map((c) => `\n${scriptConstraintCreate(t, c)}`)
                        .join("") +
                    tableComments(t),
            ),
        ]),
        sequenceOwners: sequences
            .map((s) => `ALTER SEQUENCE ${s.qualifiedName} OWNED BY ${s.ownedBy};\n`)
            .join(""),
        rest: join(
            tables.flatMap((t) => [
                ...lateConstraints(t, true).map((c) => scriptConstraintCreate(t, c)),
                ...indexesWithoutConstraint(t).map((i) => scriptIndexCreate(t, i)),
                ...t.triggers.map((tr) => scriptTriggerCreate(t.qualifiedName, tr)),
                rowSecurity(t).replace(/^\n/, ""),
            ]),
        ),
    };
}

/** "Script as Create" of a table: sequences, table, partitions, keys, indexes, triggers, comments. */
export function scriptTableCreate(table: PgTable): string {
    const parts = tableScriptParts(table);
    return [parts.table, parts.sequenceOwners, parts.rest].filter((t) => t !== "").join("\n");
}

export const scriptTableDrop = (table: { qualifiedName: string }) =>
    `DROP TABLE IF EXISTS ${table.qualifiedName};\n`;

